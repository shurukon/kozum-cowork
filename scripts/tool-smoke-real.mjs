function generated(schema, name) {
  if (!schema || schema.type !== "object") return {};
  const out = {};
  for (const [key, prop] of Object.entries(schema.properties ?? {})) {
    if (prop.default !== undefined) out[key] = prop.default;
    else if (prop.enum?.length) out[key] = prop.enum[0];
    else if (prop.type === "string") out[key] = key.toLowerCase().includes("path") ? "." : `smoke-${name}-${key}`;
    else if (prop.type === "number" || prop.type === "integer") out[key] = 1;
    else if (prop.type === "boolean") out[key] = false;
    else if (prop.type === "array") out[key] = [];
    else if (prop.type === "object") out[key] = {};
  }
  return out;
}

function contentOf(value) {
  if (value && typeof value === "object") {
    if (typeof value.content === "string") return value.content;
    if (typeof value.error === "string") return value.error;
    if (typeof value.message === "string") return value.message;
  }
  const serialized = typeof value === "string" ? value : JSON.stringify(value ?? "");
  return String(serialized ?? "");
}
function idFrom(value, pattern) {
  const match = pattern.exec(contentOf(value));
  return match?.[1] ?? "";
}
function dynamicInput(name, tool) {
  const input = { ...(overrides[name] ?? generated(tool.inputSchema, name)) };
  if (name.startsWith("shell_job_") && name !== "shell_job_list") {
    input.jobId = name === "shell_job_kill" ? state.killJobId : state.backgroundJobId;
  }
  if (name === "memory_read" || name === "memory_delete") input.id = state.memoryId;
  if (name === "process_kill") input.pid = victim.pid;
  if (["task_get", "task_update", "task_stop"].includes(name)) input.taskId = state.taskId;
  if (["schedule_run_now", "schedule_update", "schedule_delete"].includes(name)) input.id = state.scheduleId;
  if (["agent_status", "agent_cancel"].includes(name)) input.agentId = state.agentId;
  if (["plugin_enable", "plugin_disable", "plugin_uninstall"].includes(name)) input.id = state.pluginId;
  if (name === "marketplace_list") input.id = "missing-marketplace";
  return input;
}

